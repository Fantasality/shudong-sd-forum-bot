def time_context(ts: float | None = None) -> dict:
    dt = datetime.fromtimestamp(ts if ts is not None else time.time())
    h = dt.hour
    if h < 6:
        part = "凌晨"
    elif h < 9:
        part = "早上"
    elif h < 11:
        part = "上午"
    elif h < 13:
        part = "中午"
    elif h < 17:
        part = "下午"
    elif h < 19:
        part = "傍晚"
    elif h < 23:
        part = "晚上"
    else:
        part = "深夜"
    wd = "一二三四五六日"[dt.weekday()]
    return {
        "text": f"{dt.strftime('%Y-%m-%d')} 周{wd} {dt.strftime('%H:%M')}（{part}）",
        "weekday": f"周{wd}",
        "hour": h,
        "part": part,
        "date": dt.strftime("%Y-%m-%d"),
    }


def subtopic_index(cfg: dict) -> dict:
    """{subtopic_id: (topic_name, topic_id, subtopic_name)}"""
    idx = {}
    for tname, t in ((cfg or {}).get("topics") or {}).items():
        for sname, sid in (t.get("subtopics") or {}).items():
            idx[sid] = (tname, t.get("id") or "", sname)
    return idx


