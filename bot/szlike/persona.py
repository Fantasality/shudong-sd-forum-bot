def _recent(store, kind: str, limit: int = 12) -> set[str]:
    if store is None:
        return set()
    try:
        return {r["target"] for r in store.list_actions(kind, limit)}
    except Exception:
        return set()


def pick_post_plan(cfg: dict, store, account: str, persona: str,
                   seed: int | None = None) -> dict:
    """时间种子随机生成一条发帖计划：场景 × 板块 × 写法。"""
    p = PERSONAS.get(persona) or PERSONAS["warm"]
    sd = seed if seed is not None else seed_now(f"{account}:post")
    r = random.Random(sd)

    used_angles = _recent(store, "pick:angle", 10)
    pool = [a for a in p["angles"] if a[0] not in used_angles] or list(p["angles"])
    angle, subs = r.choice(pool)

    idx = subtopic_index(cfg)
    # 场景自带的板块优先，且必须真实存在于配置里
    allowed = [SUB[s] for s in subs if SUB.get(s) in idx]
    if not allowed:
        allowed = [SUB[s] for s in p["subs"] if SUB.get(s) in idx]
    if not allowed:
        allowed = list(idx.keys())
    sid = r.choice(allowed)

    topic_name, topic_id, sub_name = idx.get(sid, ("校园生活", cfg.get("default_topic_id") or "", "抛抛帖子"))
    style = r.choice(STYLES)
    ctx = time_context()

    return {
        "seed": sd,
        "angle": angle,
        "style": style,
        "topic_id": topic_id,
        "subtopic_id": sid,
        "topic_name": topic_name,
        "subtopic_name": sub_name,
        "time": ctx["text"],
        "weekday": ctx["weekday"],
        "part": ctx["part"],
    }


