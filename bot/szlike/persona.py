# ---------------------------------------------------------------- 时间种子


def seed_now(salt: str = "") -> int:
    """用当前系统时间（纳秒）派生种子。"""
    return zlib.crc32(f"{time.time_ns()}:{salt}".encode("utf-8")) & 0xFFFFFFFF


def rng(salt: str = "") -> random.Random:
    return random.Random(seed_now(salt))


def weighted_sample(r: random.Random, items: list, weights: list[float], k: int) -> list:
    """无放回加权抽样。"""
    items = list(items)
    weights = [max(0.0001, float(w)) for w in weights]
    out = []
    for _ in range(min(k, len(items))):
        total = sum(weights)
        pick = r.random() * total
        acc = 0.0
        idx = len(items) - 1
        for i, w in enumerate(weights):
            acc += w
            if pick <= acc:
                idx = i
                break
        out.append(items.pop(idx))
        weights.pop(idx)
    return out


