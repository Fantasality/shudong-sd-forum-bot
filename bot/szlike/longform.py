"""超长评论 / 超长帖的写法。

数据底稿（`kb/raw.db`，18,276 条评论 / 78,510 条帖子，2026-11-04 统计）：

| 场景 | 评论 ≥100 字 | ≥150 字 |
|---|---|---|
| 全部帖子 | 2.9% | 1.1% |
| 今天不开心 | 7.8% | 3.6% |
| 恋爱 / 女孩 | **60.1%** | 59.5% |
| 长帖（≥200 字）下 | 10.9% | 5.1% |
| 超长帖（≥300 字）下 | 13.4% | 6.7% |

情绪帖长评论的长度分布：p50=142 / p75=203 / p90=342 / max=557。

**结论：长评论不是随机出现的，它是「强情感帖」的配套。**
在一句「食堂排队」下面写 200 字是神经病，在一篇写了 600 字的崩溃帖下面写 200 字
才是正常反应。所以这里不做「整体提高长度」，只做「按帖子强度决定给不给长档」。

从语料里能拆出三种长评论，和三种长帖。
"""
from __future__ import annotations

# ---------------------------------------------------------------- 长评论

# 三种写法。key 会被拼进 prompt，所以要写成能直接执行的指令。
#
# 2026-11-04 改版：**共鸣档下线**。
# 复核 kb/raw.db 情感/恋爱帖（2,947 条）下 350 条 ≥60 字评论的高赞前 120 条：
# 被赞起来的都是「给判断 + 讲道理 + 给做法」，而且带立场、带冲劲
# （「姐妹快跑」「你的喜欢也挺肤浅的」「直接抬头看着监考人员说：考试时间还没到」）。
# 高赞长评长度 p50=116 / p75=181 / p90=291。
# 而「我也一样 + 我自己的一件小事 + 停在画面上」写出来是
# 「买了一份关东煮，坐在台阶上一根一根吃完，汤都凉了」这种自我表演式细节，一眼 AI。
COMMENT_KINDS: dict[str, dict] = {
    "建议": {
        "lo": 100, "hi": 200,
        "how": (
            "第一句直接给判断或立场，别绕，也别「我也一样」，比如"
            "「异地这事别自己一个人想，先问他打算怎么办」"
            "「这事想太多没用，先弄清楚一件事」。"
            "第二句点破原因：他真正卡在哪、真正怕的是什么。"
            "然后给一条现在就能做的建议（一条就够，别列两三条），"
            "**必须带上可以直接说出口的原话**"
            "（「直接问他：你毕业打算去哪，我看看能不能对上」），"
            "或者一个具体动作（写下来、约出来当面说、定个期限、把话说死）。"
            "可以有立场，可以说「别」「不值得」「算了」，不必两边都照顾到。"
            "最后一句用一句实话收尾"
        ),
        "avoid": ("别写「我也一样」「我也是」「抱抱」「加油」「会好起来的」，"
                  "别写自己吃饭、走路、图书馆、路灯、手机这些画面，"
                  "别排比、别金句、别心理科普，别用破折号，"
                  "别用「不是…是…」「不是…而是…」这种对仗句"),
    },
    "拆解": {
        "lo": 150, "hi": 260,
        "how": (
            "把对方纠结的事拆成两个点（最多两个，别拆三个），一个一个说。"
            "每点先给一句判断（这点可以放一放 / 这点才是要紧的），再给一个具体做法，"
            "最好带上可以直接说出口的原话。可以分条，但每条都要有实质内容，"
            "不能只写「多沟通」这种空话。最后一条说完就停"
        ),
        "avoid": ("别写「1. 2. 3.」之外的层级，别写「首先其次最后」，"
                  "别加总结陈词，别写自己的画面和心情，别用破折号，"
                  "别用「不是…是…」的对仗句收尾"),
    },
    "分析": {
        "lo": 120, "hi": 220,
        "how": (
            "先给一句判断，再解释这件事为什么会这样（归到一个更普遍的原因上："
            "大家都没被教过怎么处理这种事 / 这套规则本来就这样 / 你们在意的不是同一件事）。"
            "中间可以有一句让步，承认两种想法都成立。"
            "最后必须落到一个具体建议上，最好带可以直接说出口的那句话"
        ),
        "avoid": "别说「希望能帮到你」「首先其次最后」，别写成心理科普，别写自己的画面",
    },
}

# 情绪 → 用哪种写法。没列的状态不给长档。
# 情感/恋爱/委屈/孤独一律给建议，不学共鸣。
KIND_BY_MOOD = {
    "情感": ("建议", "拆解"),
    "委屈": ("建议", "分析"),
    "孤独": ("建议", "分析"),
}


# 「想问问大家 / 大家会…吗」这类短征询帖，虽然字数不到 90，
# 但楼下本来就是长回答：#XP76（32 字，恋爱异地）已有 3 条 50-100 字的认真回复。
# 恋爱板块的长评率 60.1%，不按「帖子字数」一刀切才对。
ASK_MARKERS = (
    "想问问大家", "问问大家", "大家会", "有没有人", "你们会", "会考虑吗",
    "想问下", "想问一下", "该怎么办", "该不该", "怎么办", "有人", "求问",
)


def _asks_community(text: str) -> bool:
    return any(m in text for m in ASK_MARKERS)


def plan_comment(text: str, mp: dict, rng=None) -> dict | None:
    """强情感帖才给长档。返回 None 表示这条按普通长度写。

    概率来自语料：情绪帖下 60% 的评论超过 100 字，但其中一半是「玩梗复读」
    和「一句话站队」，我们只学「认真写」的那部分，所以给到 55%-65%。
    短的征询帖另外开一道小口子（30%）：它在问「大家会怎么做」，长回答是自然反应。
    """
    mood = (mp or {}).get("mood") or ""
    kinds = KIND_BY_MOOD.get(mood)
    if not kinds:
        return None
    t = (text or "").strip()
    n = len(t)
    ask = n < 90 and _asks_community(t)
    if n < 90 and not ask:
        return None                      # 一句话的陈述帖配 200 字评论，反而假
    p = 0.30 if ask else (0.45 if n < 250 else (0.6 if n < 400 else 0.7))
    if rng is not None and rng.random() >= p:
        return None
    kind = kinds[0] if rng is None else rng.choice(kinds)
    spec = COMMENT_KINDS[kind]
    return {"kind": kind, "lo": spec["lo"], "hi": spec["hi"], "how": spec["how"],
            "avoid": spec["avoid"], "p": p}


def brief_comment(lf: dict) -> str:
    """拼成给模型的长度+写法指令。

    这里绝不能出现「不用句号」：`Ctx.prompt(long_text=True)` 用
    `re.sub(r"\\n?[^\\n]*不用句号[^\\n]*", "", system)` 删人设里写死的短内容规矩，
    一旦本行也带这四个字，整行「要求 + avoid + 分段」会被一起删掉。
    语料里 ≥100 字评论 58% 有句号，长评本来就该正常断句。
    """
    return (f"【这条要写长一点：{lf['lo']}-{lf['hi']} 字，别超过 {lf['hi']} 字】{lf['how']}。\n"
            f"要求：{lf['avoid']}。用句号正常断句，分成两三段，每段之间空一行，"
            "不要写成一大坨。结尾用一句实话收住，"
            "不要总结陈词、不要升华，尤其不要用「吃烤肠/关东煮/汤凉了」这类画面感收尾。")


def mood_note(mp: dict) -> str:
    """长评的姿态：这条要给对方真东西。

    `mood.brief()` 给的是「说一句你在」「不分析也不劝」这类短评指令，
    跟「判断 + 分析 + 建议」直接打架，所以长文档位下换成这一条。
    """
    return (f"【这条的情绪】{(mp or {}).get('mood') or '日常'}。"
            "这条要给对方真东西：一个判断、一点分析、一条能照做的建议。"
            "别只陪着叹气，别写自己的画面，别鸡汤。")


# ---------------------------------------------------------------- 长帖

POST_KINDS: dict[str, dict] = {
    "倾诉": {
        "lo": 280, "hi": 650,
        "how": (
            "想到哪写到哪，像深夜发给朋友的一段话。从事情本身起手"
            "（发生了什么、跟谁有关、现在卡在哪），然后顺着情绪往下走，中间可以跳、"
            "可以回头补一句。不分段或者只分一两段。结尾停在这件事的现状上，"
            "不要总结、不要给自己打气"
        ),
    },
    "时间线": {
        "lo": 400, "hi": 800,
        "how": (
            "按时间分段：大一上、大一下、大二上这样，每段讲这段时间发生了什么、"
            "状态怎么变的。写清关键事实（成绩、次数、结果），没有的别编。"
            "段与段之间空一行"
        ),
    },
    "剖析": {
        "lo": 320, "hi": 700,
        "how": (
            "先给一个关于自己的结论（「我一直是个…的人」），再往回找原因"
            "（小时候、家里、某件事），然后拿别人的相处方式做对比，说明自己为什么不一样。"
            "中间要承认一次自己的矛盾（「一边…一边…」）"
        ),
    },
}

POST_COMMON = (
    "长文有长文的写法：大量用「我」；把关键事实写清楚（时间、地点、跟谁、结果），"
    "没有的不编；"
    "想到一半可以自己打断、自己修正（加个括号补一句）；"
    "允许有废话和重复，真人写这么长的时候不会打磨句子；"
    "结尾不要升华、不要金句，停在这件事现在的状态上就行"
)


def plan_post(text: str, mp: dict, rng=None) -> dict | None:
    """发帖侧的长文。只有强情绪话题才给，概率很低。

    语料里 ≥300 字的帖子只占 0.76%，不能天天写，但一个号一个月出一两篇
    会让人设立体很多。
    """
    mood = (mp or {}).get("mood") or ""
    if mood not in ("情感", "委屈", "孤独"):
        return None
    p = 0.06
    if rng is not None and rng.random() >= p:
        return None
    kind = "倾诉" if rng is None else rng.choice(list(POST_KINDS))
    spec = POST_KINDS[kind]
    return {"kind": kind, "lo": spec["lo"], "hi": spec["hi"], "how": spec["how"]}


def brief_post(lf: dict) -> str:
    return (f"【这条写长一点：{lf['lo']}-{lf['hi']} 字】{lf['how']}。\n"
            f"{POST_COMMON}。")
