"""读帖子的情绪，决定用什么姿态回。

原来的 `rag.classify` 回答的是「这条帖子在讲什么事」，分出 16 个场景。
但它不回答另一个问题：**发帖的人现在是什么状态，我该用什么姿态接**。
所以模型永远收到同一句「接住对方的情绪」——抱怨的帖子也接、愤怒的帖子也接、
失恋的帖子还接，结果全是客服腔。

这里把「场景」拆成两件事：

- **mood**：发帖人现在的状态（抱怨 / 愤怒 / 委屈 / 情感 / 孤独 / 求助 / 分享 / 日常）
- **stance**：这一条该用什么姿态（一起骂 / 话里有话 / 哥们抱抱 / 一起拆开分析 / 给办法 / 接梗）

性别只在情感类里判，因为它决定姿态：男生诉苦要「抱一下，别分析」，
女生诉苦要「把卡住的那点拆开，再给一句轻的安慰」。判不出来就走中性，
宁可平一点，也不要猜错性别——猜错比不猜更假。
"""
from __future__ import annotations

