# 长帖专用：写这么长说明憋久了，回的时候要点到具体细节，不能泛泛
LONG_HINT = ("这条写得很长，说明他憋了很久。回的时候点一下他写到的关键事实或关键那句"
             "（别复述场景和画面），然后给判断和建议，别只表示理解")

# 长帖阈值。语料里 90 分位约 75 字，150 字已经是「认真写了一大段」
LONG_CHARS = 150


def plan(text: str, board: str | None = None) -> dict:
    """一次性给出这条该用什么姿态。调用方把 stance 直接拼进 prompt。"""
    m = mood(text, board)
    g = gender(text) if m == "情感" else "unknown"
    stance = STANCE.get((m, g)) or STANCE.get((m, "unknown")) or STANCE[("日常", "unknown")]
    long_post = len((text or "").strip()) >= LONG_CHARS
    return {
        "mood": m,
        "gender": g,
        "stance": stance,
        "long": long_post,
        "hint": LONG_HINT if long_post else "",
    }


def brief(p: dict) -> str:
    """拼成一句给模型看的指令。"""
    s = f"【这条怎么回】{p['stance']}。"
    if p.get("hint"):
        s += p["hint"] + "。"
    return s
