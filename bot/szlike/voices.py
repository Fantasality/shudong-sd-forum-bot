_P = "你是{who}。你在校园社区发一条日常帖子。"
_TAIL = "只输出帖子正文，不要引号、不要解释、不暴露 AI 身份。"


def prompts(key: str) -> dict:
    s = SPECS[key]
    rules = "\n".join(f"- {r}" for r in s["rules"])
    post_sys = (f"{_P.format(who=s['role'])}\n要求：\n{rules}\n"
                f"- 不用 emoji，不用句号\n{_TAIL}")
    comment_sys = (f"你是{s['role']}，正在刷校园社区。留一句评论。\n"
                   f"要求：{s['comment_rule']}；不客套、不复读标题、不暴露 AI。"
                   "只输出评论本身。")
    reply_sys = (f"你在大学社区回复别人的评论。{s['reply_rule']}。"
                 "不客套、不暴露 AI。只输出回复本身。")
    return {
        "post": {"label": f"发帖 · {s['label']}", "system": post_sys,
                 "user": "现在是 {time}。\n发在「{topic}」板块。\n这次写这个：{angle}\n写法：{style}\n{seed}", "enabled": True},
        "comment": {"label": f"评论 · {s['label']}", "system": comment_sys,
                    "user": "帖子：{post}\n写法：{style}", "enabled": True},
        "reply": {"label": f"回复 · {s['label']}", "system": reply_sys,
                  "user": "帖子：{post}\n对方说：{their}", "enabled": True},
    }


